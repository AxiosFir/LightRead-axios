// Approved App v3 prototype: inline personal lists and grouped sources.
// Start a mobile build/dev server; E2E_BASE defaults to http://localhost:4192.
import assert from 'node:assert/strict'
import { mkdirSync, writeFileSync } from 'node:fs'
import { chromium } from 'playwright'
const base = process.env.E2E_BASE || 'http://localhost:4192'
const out = process.env.SHOTS_DIR || '/tmp/lightread-mobile-booklists'
mkdirSync(out, { recursive: true })
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 392, height: 872 } })
page.setDefaultTimeout(10000)
const errors = [], checks = []
page.on('pageerror', e => errors.push(e.message))
await page.addInitScript(() => {
  const s = JSON.parse(localStorage.getItem('lightread-settings') || '{}')
  s.features = { ...s.features, recommendedBooklists: true }
  localStorage.setItem('lightread-settings', JSON.stringify(s))
})
// Local search and bundled curated lists are real; remote failure is deterministic.
await page.route('**/*', r => r.request().url().startsWith(base + '/') ? r.continue() : r.abort())
const go = async route => {
  await page.goto(base + '/#' + route)
  await page.locator(route.startsWith('/catalogs') ? '.source-group' : '.library').first().waitFor()
  await page.waitForFunction(() => document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s.get('library')?.loaded)
}
const lists = () => page.locator('.shelf-filters').getByRole('button', { name: '书单', exact: true })
const dialog = () => page.getByRole('dialog')
const create = async name => {
  await page.locator('.booklist-create').click()
  assert.ok(await dialog().getByRole('button', { name: '创建书单', exact: true }).isDisabled())
  await dialog().getByRole('textbox').fill(name)
  await dialog().getByRole('button', { name: '创建书单', exact: true }).click()
  await page.locator('.booklist-tile').filter({ hasText: name }).waitFor()
}
const state = () => page.evaluate(() => JSON.parse(JSON.stringify(document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s.get('library').$state)))
const check = text => { checks.push(text); console.log('PASS', text) }
async function layout(name) {
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), name + ': document overflow')
  const bad = await page.locator('.booklist-tile:visible,.booklist-create:visible,.public-source-row:visible,.personal-booklist-row:visible,.scope-choose:visible').evaluateAll(els => els.filter(el => {
    const r = el.getBoundingClientRect(); return r.width > innerWidth + 1 || r.height < 44 || r.left < -1 || r.right > innerWidth + 1
  }).map(el => el.textContent))
  assert.deepEqual(bad, [], name + ': clipped or undersized controls')
  await page.screenshot({ path: `${out}/${name}.png`, animations: 'disabled' })
}
try {
  await go('/library')
  await lists().click()
  assert.equal(await dialog().count(), 0)
  assert.equal(await page.locator('.booklist-row').count(), 0)
  await page.locator('.booklist-overview-empty').waitFor()
  await create('慢慢读')
  await page.locator('.booklist-tile').click()
  await page.locator('.booklist-empty').waitFor()
  await page.getByRole('button', { name: '返回书单', exact: true }).click()
  await create('待读')
  check('书单作为页内列表；新建、空书单、返回与零藏书均可用')
  await page.locator('input[type=file]').first().setInputFiles({ name: '长篇测试.txt', mimeType: 'text/plain', buffer: Buffer.from('第一章 理想与城邦\n\n' + '这是书单浏览回归测试用的正文。'.repeat(200)) })
  await page.waitForFunction(() => document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s.get('library').books.length === 1)
  await page.evaluate(async () => {
    const l = document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s.get('library')
    const id = l.booklists.find(x => x.name === '慢慢读').id
    await l.addBooksToBooklist(id, [l.books[0].id])
    await l.addEntriesToBooklist(id, [{ title: '待找图书', author: '测试作者' }])
  })
  await lists().click()
  const tile = page.locator('.booklist-tile').filter({ hasText: '慢慢读' })
  assert.match(await tile.innerText(), /1 本.*待找 1 本/s)
  await tile.click()
  assert.equal(await page.locator('.book-card').count(), 1)
  await page.locator('.wanted-card').filter({ hasText: '待找图书' }).waitFor()
  await page.locator('.book-card').click()
  await page.waitForFunction(() => document.querySelector('foliate-view')?.renderer?.getContents?.().length)
  await page.goBack()
  await page.getByRole('button', { name: '返回书单', exact: true }).waitFor()
  assert.equal(await page.locator('.book-card').count(), 1, 'return from reader keeps selected booklist')
  await page.getByRole('button', { name: '返回书单', exact: true }).click()
  await page.locator('.booklist-overview-head').getByRole('button', { name: '管理', exact: true }).click()
  const row = dialog().locator('.booklist-manage-row').filter({ has: page.locator('input') }).first()
  const original = await row.locator('input').inputValue()
  await row.locator('input').fill(original + '·改名')
  await row.getByRole('button', { name: '保存', exact: true }).click()
  await dialog().getByRole('button', { name: '关闭', exact: true }).click()
  assert.ok((await state()).booklists.some(x => x.name === original + '·改名'))
  const search = page.locator('input[type=search]').first()
  await search.fill('不存在的书单')
  assert.equal(await page.locator('.booklist-tile').count(), 0)
  await page.locator('.booklist-overview-empty').waitFor()
  await search.fill('慢慢读')
  assert.equal(await page.locator('.booklist-tile').count(), 1)
  await search.fill('')
  check('真实藏书计数、待找条目、进入内容、改名和书单搜索')
  for (const theme of ['light', 'dark']) {
    await page.evaluate(theme => { document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s.get('settings').appearance = theme }, theme)
    for (const width of [320, 375, 414, 768]) {
      await page.setViewportSize({ width, height: 900 })
      await go('/library?view=booklists')
      await page.locator('.booklist-tile').first().waitFor()
      await page.locator('.recommended-booklists .curated-card').first().waitFor()
      await layout(`lists-${theme}-${width}`)
      await go('/catalogs')
      assert.deepEqual(await page.locator('.source-group').evaluateAll(els => els.map(el => el.dataset.sourceGroup)), ['public', 'private'])
      assert.equal(await page.locator('.main-public-source').count(), 4)
      assert.equal(await page.locator('.personal-booklist-row').count(), 2)
      assert.equal(await page.locator('.curated-card').count(), 0)
      await layout(`sources-${theme}-${width}`)
      await page.locator('.scope-summary button').click()
      assert.equal(await dialog().getByRole('checkbox').count(), 8)
      await layout(`scope-${theme}-${width}`)
      await page.keyboard.press('Escape')
      await dialog().waitFor({ state: 'hidden' })
    }
  }
  check('320/375/414/768 浅深色，书单、书源、范围窗口 24 个布局无越界')
  await page.setViewportSize({ width: 392, height: 872 })
  await page.locator('.scope-summary button').click()
  for (const box of await dialog().getByRole('checkbox').all()) await box.uncheck()
  await dialog().getByRole('button', { name: '完成', exact: true }).click()
  await page.getByRole('searchbox', { name: '统一搜书' }).fill('理想国')
  assert.ok(await page.locator('.uni-submit').isDisabled())
  await page.locator('.extra-public-sources summary').click()
  assert.equal(await page.locator('.extra-public-sources .public-source-row:visible').count(), 4)
  await page.locator('.extra-public-sources').getByRole('button', { name: /哲学文库/ }).click()
  await dialog().getByRole('searchbox').fill('共產黨宣言')
  await dialog().getByRole('button', { name: '搜索', exact: true }).click()
  await page.locator('.uni-group').filter({ hasText: '哲学文库' }).getByText('共产党宣言', { exact: true }).first().waitFor()
  await page.locator('.scope-summary button').click()
  assert.equal(await dialog().getByRole('checkbox').evaluateAll(els => els.filter(e => e.checked).length), 1)
  assert.ok(await dialog().getByRole('checkbox', { name: '哲学文库', exact: true }).isChecked())
  await page.keyboard.press('Escape')
  check('范围取消全选禁用搜索；额外公共书源可展开并完成单源真实索引搜索')
  await page.locator('.personal-booklists .scope-choose').click()
  await page.locator('.booklist-overview').waitFor()
  await go('/catalogs')
  await page.locator('.personal-booklist-row').filter({ hasText: '慢慢读' }).click()
  await page.locator('.book-card').waitFor()
  assert.equal(await page.locator('.wanted-card').count(), 1)
  await go('/catalogs')
  assert.equal(await page.locator('.curated-card').count(), 0)
  await go('/library?view=booklists')
  await page.locator('.curated-card').first().click()
  await page.locator('.curated-hero').waitFor()
  assert.ok(page.url().includes('/library?'))
  assert.ok(await page.locator('.curated-book').count() > 0)
  await page.locator('.curated-book').filter({ has: page.getByRole('button', { name: '找书', exact: true }) }).first().getByRole('button', { name: '找书', exact: true }).click()
  await page.locator('.uni-input').waitFor()
  assert.ok((await page.locator('.uni-input').inputValue()).length)
  await page.goBack()
  await page.locator('.curated-hero').waitFor()
  await page.locator('.curated-add').click()
  await page.waitForFunction(() => document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s.get('library').booklists.length === 3)
  const added = (await state()).booklists.find(x => !x.name.includes('慢慢读') && x.name !== '待读')
  assert.ok(added)
  await page.locator('.curated-add').click()
  assert.equal((await state()).booklists.length, 3, 'repeated add reuses same list')
  await page.locator('.curated-back').click()
  await page.locator('.curated-card').first().waitFor()
  check('推荐在藏书书单；详情、找书返回、加入和重复加入可用')
  await go('/catalogs')
  await page.locator('.add-source-card').click()
  await dialog().waitFor()
  assert.ok(await dialog().getByRole('button', { name: '添加', exact: true }).isDisabled())
  for (const value of ['not-a-valid-url', 'javascript:alert(1)', 'file:///tmp/book']) {
    await page.locator('#src-url').fill(value)
    await dialog().getByRole('button', { name: '添加', exact: true }).click()
    await page.locator('#src-url-error').waitFor()
    assert.equal(await page.locator('#src-url').getAttribute('aria-invalid'), 'true')
  }
  await page.locator('#src-url').fill('https://example.invalid/opds')
  assert.equal(await page.locator('#src-url-error').count(), 0)
  await dialog().getByRole('button', { name: '取消', exact: true }).click()
  assert.equal(await page.locator('.source-card.custom').count(), 0, 'invalid addresses never saved')
  assert.equal(await dialog().count(), 0)
  check('个人书单直达、管理、推荐详情进入与返回、私人书库添加取消')
  assert.deepEqual(errors, [])
  writeFileSync(`${out}/results.json`, JSON.stringify({ ok: true, checks, errors }, null, 2))
} catch (e) {
  await page.screenshot({ path: `${out}/failure.png` })
  writeFileSync(`${out}/results.json`, JSON.stringify({ ok: false, checks, errors, failure: String(e.stack) }, null, 2))
  throw e
} finally { await browser.close() }
